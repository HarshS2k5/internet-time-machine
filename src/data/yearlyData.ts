// Helper to get or generate full dataset for any year between 1980 and 2026
export function getYearData(year: number): YearData {
  const exact = KEY_YEARS_DATA.find(y => y.year === year);
  if (exact) return exact;

  // Interpolate closest year with intelligent fallback
  const sorted = [...KEY_YEARS_DATA].sort((a, b) => Math.abs(a.year - year) - Math.abs(b.year - year));
  const closest = sorted[0];

  const eraId = year < 1990 ? 'dawn-80s' 
    : year < 2000 ? 'wild-web-90s' 
    : year < 2010 ? 'dotcom-2000s' 
    : year < 2020 ? 'mobile-social-2010s' 
    : 'ai-modern-2020s';

  const eraNames: Record<string, string> = {
    'dawn-80s': 'The Dawn of Networking',
    'wild-web-90s': 'The Wild Web & Dot-Com Boom',
    'dotcom-2000s': 'Broadband, Web 2.0 & The Smartphone',
    'mobile-social-2010s': 'The App Ecosystem & Cloud Streaming',
    'ai-modern-2020s': 'Generative AI & The Spatial Web',
  };

  const yearEvents = HISTORICAL_EVENTS.filter(e => e.year === year);

  return {
    year,
    eraId,
    eraName: eraNames[eraId],
    headline: yearEvents.length > 0 ? yearEvents[0].headline : `${year}: Developments in Internet & Technology`,
    summary: yearEvents.length > 0 
      ? yearEvents[0].description 
      : `In ${year}, digital technology and the internet continued rapid evolution during ${eraNames[eraId]}.`,
    webDesignStyle: closest.webDesignStyle,
    internetSpeed: closest.internetSpeed,
    activeUsers: closest.activeUsers,
    popularWebsites: closest.popularWebsites,
    popularGames: closest.popularGames,
    majorDevices: closest.majorDevices,
    socialPlatforms: closest.socialPlatforms,
    culturalTrends: closest.culturalTrends,
    keyEvents: yearEvents,
  };
}

export const ALL_YEARS = Array.from({ length: 2026 - 1983 + 1 }, (_, i) => 1983 + i);
