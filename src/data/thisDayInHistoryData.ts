export function getTodayEvent(customDate?: Date): ThisDayEvent {
  const target = customDate || new Date();
  const currentMonth = target.getMonth() + 1; // 1-12
  const currentDay = target.getDate();

  // Try exact match
  const exact = THIS_DAY_EVENTS.find(e => e.month === currentMonth && e.day === currentDay);
  if (exact) return exact;

  // Try same month
  const sameMonth = THIS_DAY_EVENTS.filter(e => e.month === currentMonth);
  if (sameMonth.length > 0) {
    // Pick closest day
    return sameMonth.reduce((prev, curr) => 
      Math.abs(curr.day - currentDay) < Math.abs(prev.day - currentDay) ? curr : prev
    );
  }

  // Fallback to closest event overall
  return THIS_DAY_EVENTS[0];
}
